// ============================================================
// MAP CONFIG
// ============================================================

import * as tropicalVillage
    from "./tropical-village/maze.config";


// ============================================================
// ALL MAPS
// ============================================================

export const MAPS = {

    "tropical-village":
        tropicalVillage,

} as const;


// ============================================================
// MAP ID
// ============================================================

export type MapId =
    keyof typeof MAPS;


// ============================================================
// GET MAP
// ============================================================

export function getMapConfig(
    mapId: MapId
) {

    return MAPS[mapId];

}