// ============================================================
// TYPES
// ============================================================

export type MazeCell =
    | "#"
    | "."
    | "P";


// ============================================================
// GET CELL
// ============================================================

export function getMazeCell(
    cellX: number,
    cellZ: number
): MazeCell {

    if (
        cellZ < 0 ||
        cellZ >= MAZE_MAP.length
    ) {
        return "#";
    }

    const row =
        MAZE_MAP[cellZ];

    if (
        cellX < 0 ||
        cellX >= row.length
    ) {
        return "#";
    }

    return row[cellX] as MazeCell;
}


// ============================================================
// WALKABLE
// ============================================================

export function isWalkableCell(
    cellX: number,
    cellZ: number
): boolean {

    return (
        getMazeCell(
            cellX,
            cellZ
        ) !== "#"
    );
}


// ============================================================
// WORLD → CELL
// ============================================================

export function worldToCell(
    x: number,
    z: number
) {

    const cellX =
        Math.round(
            x / CELL_SIZE
        ) +
        Math.floor(
            MAP_WIDTH / 2
        );

    const cellZ =
        Math.round(
            z / CELL_SIZE
        ) +
        Math.floor(
            MAP_HEIGHT / 2
        );

    return {
        cellX,
        cellZ,
    };
}


// ============================================================
// CELL → WORLD
// ============================================================

export function cellToWorld(
    cellX: number,
    cellZ: number
) {

    return {
        x:
            (
                cellX -
                Math.floor(
                    MAP_WIDTH / 2
                )
            ) *
            CELL_SIZE,

        z:
            (
                cellZ -
                Math.floor(
                    MAP_HEIGHT / 2
                )
            ) *
            CELL_SIZE,
    };
}


// ============================================================
// WORLD POSITION COLLISION
// ============================================================

export function canMoveTo(
    x: number,
    z: number,
    radius = 0.35
): boolean {

    const points = [
        [x - radius, z - radius],
        [x + radius, z - radius],
        [x - radius, z + radius],
        [x + radius, z + radius],
    ];


    for (
        const [pointX, pointZ]
        of points
    ) {

        const cell =
            worldToCell(
                pointX,
                pointZ
            );


        if (
            !isWalkableCell(
                cell.cellX,
                cell.cellZ
            )
        ) {
            return false;
        }
    }


    return true;
}