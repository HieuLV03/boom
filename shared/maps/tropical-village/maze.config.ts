// ============================================================
// TYPES
// ============================================================

export type MazeCell =
    | "#"
    | "."
    | "P";


// ============================================================
// GET CELL
// ============================================================

export function getMazeCell(
    cellX: number,
    cellZ: number,
): MazeCell {

    if (
        cellZ < 0 ||
        cellZ >= MAZE_MAP.length
    ) {
        return "#";
    }

    const row = MAZE_MAP[cellZ];

    if (
        cellX < 0 ||
        cellX >= row.length
    ) {
        return "#";
    }

    return row[cellX] as MazeCell;
}


// ============================================================
// WALKABLE
// ============================================================

export function isWalkableCell(
    cellX: number,
    cellZ: number,
): boolean {

    return getMazeCell(
        cellX,
        cellZ,
    ) !== "#";
}


// ============================================================
// WORLD -> CELL
// ============================================================

export function worldToCell(
    x: number,
    z: number,
) {

    const cellX =
        Math.floor(
            x / CELL_SIZE +
            0.5
        ) +
        Math.floor(MAP_WIDTH / 2);

    const cellZ =
        Math.floor(
            z / CELL_SIZE +
            0.5
        ) +
        Math.floor(MAP_HEIGHT / 2);

    return {
        cellX,
        cellZ,
    };
}

// ============================================================
// CELL -> WORLD
// ============================================================

export function cellToWorld(
    cellX: number,
    cellZ: number,
) {

    return {
        x:
            (
                cellX -
                Math.floor(MAP_WIDTH / 2)
            ) *
            CELL_SIZE,

        z:
            (
                cellZ -
                Math.floor(MAP_HEIGHT / 2)
            ) *
            CELL_SIZE,
    };
}


// ============================================================
// COLLISION
// ============================================================
export function canMoveTo(
    x: number,
    z: number,
    radius = 0.45,
): boolean {

    const center =
        worldToCell(
            x,
            z,
        );

    // ========================================================
    // CHECK NEARBY CELLS
    // ========================================================

    for (
        let offsetZ = -1;
        offsetZ <= 1;
        offsetZ++
    ) {

        for (
            let offsetX = -1;
            offsetX <= 1;
            offsetX++
        ) {

            const cellX =
                center.cellX +
                offsetX;

            const cellZ =
                center.cellZ +
                offsetZ;

            // ------------------------------------------------
            // WALKABLE
            // ------------------------------------------------

            if (
                isWalkableCell(
                    cellX,
                    cellZ,
                )
            ) {
                continue;
            }

            // ------------------------------------------------
            // WALL CENTER
            // ------------------------------------------------

            const wall =
                cellToWorld(
                    cellX,
                    cellZ,
                );

            const half =
                CELL_SIZE / 2;

            const minX =
                wall.x - half;

            const maxX =
                wall.x + half;

            const minZ =
                wall.z - half;

            const maxZ =
                wall.z + half;

            // ------------------------------------------------
            // CLOSEST POINT
            // ------------------------------------------------

            const closestX =
                Math.max(
                    minX,
                    Math.min(
                        x,
                        maxX,
                    ),
                );

            const closestZ =
                Math.max(
                    minZ,
                    Math.min(
                        z,
                        maxZ,
                    ),
                );

            // ------------------------------------------------
            // DISTANCE
            // ------------------------------------------------

            const dx =
                x - closestX;

            const dz =
                z - closestZ;

            const distanceSquared =
                dx * dx +
                dz * dz;

            // ------------------------------------------------
            // COLLISION
            // ------------------------------------------------

            if (
                distanceSquared <
                radius * radius
            ) {

                return false;
            }
        }
    }

    return true;
}
